import { access, mkdir, readFile, writeFile } from 'node:fs/promises';
import { constants } from 'node:fs';
import { join } from 'node:path';

const modules = [
  'Config', 'Utils', 'Security', 'Auth', 'Users', 'Marketplace', 'Commissions',
  'Orders', 'Crypto', 'Payments', 'Wallet', 'Withdrawals', 'Meetings', 'Streams',
  'Notifications', 'Admin', 'Bootstrap', 'Code',
];
const sourceDirectory = 'backend-src';
await mkdir(sourceDirectory, { recursive: true });

async function exists(path) { try { await access(path, constants.F_OK); return true; } catch { return false; } }

const sections = [];
for (const name of modules) {
  const archivedSource = join(sourceDirectory, `${name}.js`);
  const modularSource = join('apps-script', `${name}.gs`);
  const source = await exists(archivedSource) ? archivedSource : modularSource;
  if (!(await exists(source))) throw new Error(`Missing backend module: ${name}`);
  const code = (await readFile(source, 'utf8')).trim();
  await writeFile(archivedSource, `${code}\n`, 'utf8');
  sections.push(`// =============================================================================\n// MODULE: ${name}\n// =============================================================================\n\n${code}`);
}

const banner = `/**
 * PROJECT GALAXY — SINGLE-FILE GOOGLE APPS SCRIPT BACKEND
 * Generated by: npm run build:apps-script
 * Deploy this file as Code.gs. Do not upload backend-src/*.js to Apps Script.
 * Source modules are ordered below and remain separated by MODULE headers.
 */`;
await writeFile(join('apps-script', 'Code.gs'), `${banner}\n\n${sections.join('\n\n')}\n`, 'utf8');
console.log(`Generated apps-script/Code.gs from ${modules.length} modules.`);
