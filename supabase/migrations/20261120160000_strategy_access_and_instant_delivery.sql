-- Only two non-sensitive availability flags are readable through Realtime.
create table if not exists public.trade_strategy_access (
 strategy text primary key check(strategy in ('OPUS','RANGE777')),
 enabled boolean not null, updated_at timestamptz not null default now()
);
alter table public.trade_strategy_access enable row level security;
revoke all on public.trade_strategy_access from public,anon,authenticated;
grant select on public.trade_strategy_access to authenticated;
grant all on public.trade_strategy_access to service_role;
drop policy if exists trade_strategy_access_read on public.trade_strategy_access;
create policy trade_strategy_access_read on public.trade_strategy_access for select to authenticated using(true);
insert into public.trade_strategy_access(strategy,enabled)
select 'OPUS',enabled and signals_enabled from public.scanner_streams where id='xauusd-5m'
union all select 'RANGE777',enabled and signals_enabled from public.range_scanner_state where id
on conflict(strategy) do update set enabled=excluded.enabled,updated_at=now();

create or replace function public.sync_trade_strategy_access() returns trigger
language plpgsql security definer set search_path=public as $$
begin
 insert into public.trade_strategy_access(strategy,enabled)
 values(case when tg_table_name='scanner_streams' then 'OPUS' else 'RANGE777' end,new.enabled and new.signals_enabled)
 on conflict(strategy) do update set enabled=excluded.enabled,updated_at=clock_timestamp();
 return new;
end;$$;
drop trigger if exists scanner_strategy_access on public.scanner_streams;
create trigger scanner_strategy_access after update of enabled,signals_enabled on public.scanner_streams
for each row when(new.id='xauusd-5m') execute function public.sync_trade_strategy_access();
drop trigger if exists range_strategy_access on public.range_scanner_state;
create trigger range_strategy_access after update of enabled,signals_enabled on public.range_scanner_state
for each row execute function public.sync_trade_strategy_access();

create or replace function public.get_trade_strategy_access() returns jsonb
language plpgsql stable security definer set search_path=public as $$
declare u uuid:=public.require_registered_member();
begin
 return (select jsonb_object_agg(strategy,enabled)||jsonb_build_object('updatedAt',max(updated_at)) from public.trade_strategy_access);
end;$$;
create or replace function public.assert_trade_strategy_active(p_strategy text) returns void
language plpgsql stable security definer set search_path=public as $$
begin
 if not exists(select 1 from public.trade_strategy_access where strategy=p_strategy and enabled) then
  raise exception 'Esta estrategia está temporalmente desactivada.' using errcode='42501';
 end if;
end;$$;
revoke execute on function public.sync_trade_strategy_access(),public.assert_trade_strategy_active(text),public.get_trade_strategy_access() from public,anon,authenticated;
grant execute on function public.get_trade_strategy_access() to authenticated;
do $$begin
 if exists(select 1 from pg_publication where pubname='supabase_realtime') and not exists(
  select 1 from pg_publication_tables where pubname='supabase_realtime' and schemaname='public' and tablename='trade_strategy_access') then
  alter publication supabase_realtime add table public.trade_strategy_access;
 end if;
end;$$;

-- Reserve at most one send/second per recipient, and 20/minute per group.
-- Short bursts no longer incur an unconditional 3.1-second delay per event.
create table if not exists public.scanner_telegram_send_slots (
 id bigint generated by default as identity primary key,
 recipient_id bigint not null, reserved_at timestamptz not null default now(),
 job_id bigint not null references public.scanner_telegram_jobs(id) on delete cascade
);
create index if not exists scanner_telegram_slots_recipient_idx on public.scanner_telegram_send_slots(recipient_id,reserved_at);
alter table public.scanner_telegram_send_slots enable row level security;
revoke all on public.scanner_telegram_send_slots from public,anon,authenticated;
grant all on public.scanner_telegram_send_slots to service_role;
grant usage,select on sequence public.scanner_telegram_send_slots_id_seq to service_role;
create or replace function public.claim_scanner_telegram_job() returns jsonb
language plpgsql security definer set search_path=public as $$
declare s public.scanner_telegram_settings;j public.scanner_telegram_jobs;l uuid:=gen_random_uuid();
 c bigint;r bigint;n integer;first_send timestamptz;last_send timestamptz;due timestamptz;
begin
 select * into s from public.scanner_telegram_settings where id and enabled for update skip locked;
 if not found then return null;end if;
 update public.scanner_telegram_jobs set state='expired',lease_token=null where state='pending' and expires_at<=now() and leased_until<=now();
 select * into j from public.scanner_telegram_jobs where state='pending' and attempts<8 and expires_at>now() and next_attempt_at<=now() and leased_until<=now()
 order by case when kind='EVENT' and payload->>'type'='SIGNAL' then 0 when kind='EVENT' then 1 when kind in ('WEEKLY','MONTHLY','PHOTO') then 2 else 3 end,id
 limit 1 for update skip locked;
 if not found then return null;end if;
 if s.next_send_at>now() then return jsonb_build_object('waitMs',ceil(extract(epoch from(s.next_send_at-now()))*1000));end if;
 select chat_id into c from public.telegram_community_config where id;
 r:=coalesce(j.recipient_id,c,0);
 -- Concurrent drains must not reorder messages that are already in flight.
 if exists(select 1 from public.scanner_telegram_jobs where state='pending' and lease_token is not null and leased_until>now() and coalesce(recipient_id,c,0)=r) then
  return jsonb_build_object('waitMs',250);
 end if;
 delete from public.scanner_telegram_send_slots where reserved_at<=now()-interval '60 seconds';
 select count(*),min(reserved_at),max(reserved_at) into n,first_send,last_send from public.scanner_telegram_send_slots where recipient_id=r;
 due:=coalesce(last_send+interval '1.05 seconds','-infinity');
 if r<=0 and n>=20 then due:=greatest(due,first_send+interval '60 seconds');end if;
 if due>now() then return jsonb_build_object('waitMs',ceil(extract(epoch from(due-now()))*1000));end if;
 insert into public.scanner_telegram_send_slots(recipient_id,job_id) values(r,j.id);
 update public.scanner_telegram_jobs set attempts=attempts+1,leased_until=now()+interval '60 seconds',lease_token=l where id=j.id;
 return jsonb_build_object('job',jsonb_build_object('id',j.id,'lease',l,'kind',j.kind,'payload',j.payload,'chatId',coalesce(j.recipient_id,c)));
end;$$;
revoke execute on function public.claim_scanner_telegram_job() from public,anon,authenticated;
grant execute on function public.claim_scanner_telegram_job() to service_role;

