begin;

-- Private, opt-in delivery. Installing this migration sends nothing and does
-- not replay historical events. Bot credentials live only in server secrets.
create table if not exists public.scanner_telegram_settings (
  id boolean primary key default true check(id),
  enabled boolean not null default false,
  activated_at timestamptz,
  next_send_at timestamptz not null default '-infinity',
  dispatch_until timestamptz not null default '-infinity'
);
insert into public.scanner_telegram_settings(id) values(true) on conflict do nothing;
create table if not exists public.scanner_telegram_jobs (
  id bigint generated by default as identity primary key,
  dedupe_key text not null unique,
  kind text not null check(kind in ('EVENT','WEEKLY','MONTHLY')),
  payload jsonb not null,
  state text not null default 'pending' check(state in ('pending','sent','failed','expired')),
  attempts integer not null default 0,
  next_attempt_at timestamptz not null default now(),
  leased_until timestamptz not null default '-infinity',
  lease_token uuid,
  expires_at timestamptz not null,
  created_at timestamptz not null default now(),
  sent_at timestamptz,
  telegram_message_id bigint,
  last_code text
);
create index if not exists scanner_telegram_pending_idx on public.scanner_telegram_jobs(next_attempt_at,id) where state='pending';
alter table public.scanner_telegram_settings enable row level security;
alter table public.scanner_telegram_jobs enable row level security;
revoke all on public.scanner_telegram_settings,public.scanner_telegram_jobs from public,anon,authenticated;
grant all on public.scanner_telegram_settings,public.scanner_telegram_jobs to service_role;
grant usage,select on sequence public.scanner_telegram_jobs_id_seq to service_role;

create or replace function public.dispatch_scanner_telegram() returns void
language plpgsql security definer set search_path=public,vault,net as $$
declare v_url text; v_secret text;
begin
  if not exists(select 1 from public.scanner_telegram_jobs where state='pending' and attempts<8 and expires_at>now() and next_attempt_at<=now() and leased_until<=now()) then return; end if;
  update public.scanner_telegram_settings set dispatch_until=now()+interval '25 seconds'
    where id and enabled and dispatch_until<=now();
  if not found then return; end if;
  select decrypted_secret into v_url from vault.decrypted_secrets where name='galaxy_telegram_dispatch_url' limit 1;
  select decrypted_secret into v_secret from vault.decrypted_secrets where name='galaxy_telegram_dispatch_secret' limit 1;
  if v_url is null or v_secret is null then return; end if;
  perform net.http_post(url:=v_url,headers:=jsonb_build_object('Content-Type','application/json','x-galaxy-telegram-secret',v_secret),body:='{}'::jsonb,timeout_milliseconds:=30000);
exception when others then
  -- Telegram/pg_net availability must never roll back a live scanner result.
  return;
end; $$;

create or replace function public.enqueue_scanner_telegram_event() returns trigger
language plpgsql security definer set search_path=public as $$
begin
  if not exists(select 1 from public.scanner_telegram_settings where id and enabled and new.occurred_at>=activated_at) then return new; end if;
  insert into public.scanner_telegram_jobs(dedupe_key,kind,payload,expires_at)
    values('event:'||new.id,'EVENT',jsonb_build_object('id',new.id,'tradeId',new.trade_id,'type',new.type,'occurredAt',new.occurred_at,'trade',new.payload),now()+interval '5 minutes')
    on conflict(dedupe_key) do nothing;
  perform public.dispatch_scanner_telegram();
  return new;
end; $$;
drop trigger if exists scanner_telegram_event_insert on public.scanner_events;
create trigger scanner_telegram_event_insert after insert on public.scanner_events for each row execute function public.enqueue_scanner_telegram_event();

create or replace function public.claim_scanner_telegram_job() returns jsonb
language plpgsql security definer set search_path=public as $$
declare v_settings public.scanner_telegram_settings; v_job public.scanner_telegram_jobs; v_lease uuid:=gen_random_uuid();
begin
  select * into v_settings from public.scanner_telegram_settings where id and enabled for update skip locked;
  if not found then return null; end if;
  update public.scanner_telegram_jobs set state='expired',lease_token=null where state='pending' and expires_at<=now() and leased_until<=now();
  select * into v_job from public.scanner_telegram_jobs where state='pending' and attempts<8 and expires_at>now() and next_attempt_at<=now() and leased_until<=now() order by id limit 1 for update skip locked;
  if not found then return null; end if;
  if v_settings.next_send_at>now() then return jsonb_build_object('waitMs',ceil(extract(epoch from (v_settings.next_send_at-now()))*1000)); end if;
  update public.scanner_telegram_settings set next_send_at=now()+interval '3.1 seconds' where id;
  update public.scanner_telegram_jobs set attempts=attempts+1,leased_until=now()+interval '60 seconds',lease_token=v_lease where id=v_job.id;
  return jsonb_build_object('job',jsonb_build_object('id',v_job.id,'lease',v_lease,'kind',v_job.kind,'payload',v_job.payload));
end; $$;

create or replace function public.finish_scanner_telegram_job(p_id bigint,p_lease uuid,p_status text,p_message_id bigint default null,p_retry_after integer default 0,p_code text default null) returns boolean
language plpgsql security definer set search_path=public as $$
declare v_attempts integer; v_delay integer;
begin
  if p_status not in ('sent','retry','failed') then raise exception 'Invalid delivery status'; end if;
  select attempts into v_attempts from public.scanner_telegram_jobs where id=p_id and lease_token=p_lease and state='pending' for update;
  if not found then return false; end if;
  v_delay:=least(86400,greatest(15*power(2,least(v_attempts-1,7))::integer,coalesce(p_retry_after,0)));
  update public.scanner_telegram_jobs set state=case when p_status='retry' and attempts<8 then 'pending' when p_status='retry' then 'failed' else p_status end,
    next_attempt_at=now()+make_interval(secs=>v_delay),leased_until='-infinity',lease_token=null,
    sent_at=case when p_status='sent' then now() end,telegram_message_id=p_message_id,last_code=left(p_code,32) where id=p_id;
  if p_retry_after>0 then update public.scanner_telegram_settings set next_send_at=greatest(next_send_at,now()+make_interval(secs=>least(p_retry_after,86400))) where id; end if;
  return true;
end; $$;

create or replace function public.scanner_telegram_report(p_from date,p_to date) returns jsonb
language sql stable security definer set search_path=public as $$
  with days as (select * from public.scanner_daily_statistics where day between p_from and p_to and totals[1]>0),
  ranked as (select day,totals[2] wins,totals[3] losses,totals[2]*100/(totals[2]+totals[3]) rate from days where totals[2]+totals[3]>0),
  targets as (select level,coalesce(sum((targets->level->>'gain')::numeric),0) gain,
    coalesce(sum((targets->level->>'loss')::numeric-coalesce((targets->level->>'protectedLoss')::numeric,0)),0) loss
    from generate_series(0,2) level left join days on true group by level)
  select jsonb_build_object('from',p_from,'to',p_to,'asOf',now(),'timezone','America/Bogota',
    'signals',coalesce(sum(totals[1]),0),'wins',coalesce(sum(totals[2]),0),'losses',coalesce(sum(totals[3]),0),
    'ignored',coalesce(sum(totals[4]),0),'open',coalesce(sum(totals[5]),0),'signalDays',count(*),
    'hits',jsonb_build_array(coalesce(sum(totals[8]),0),coalesce(sum(totals[9]),0),coalesce(sum(totals[10]),0)),
    'bestDay',(select jsonb_build_object('day',day,'wins',wins,'losses',losses,'rate',rate) from ranked order by rate desc,wins+losses desc,day limit 1),
    'worstDay',(select jsonb_build_object('day',day,'wins',wins,'losses',losses,'rate',rate) from ranked order by rate,wins+losses desc,day limit 1),
    'targets',(select jsonb_agg(jsonb_build_object('level',level+1,'net',(gain-loss)*10) order by level) from targets)) from days;
$$;

create or replace function public.enqueue_scanner_telegram_reports(p_now timestamptz default now()) returns void
language plpgsql security definer set search_path=public as $$
declare v_active timestamptz; v_local timestamp:=p_now at time zone 'America/Bogota'; v_start date; v_due timestamptz; v_kind text; v_key text;
begin
  select activated_at into v_active from public.scanner_telegram_settings where id and enabled;
  if not found or v_active is null then return; end if;
  update public.scanner_telegram_jobs set state=case when expires_at<=now() then 'expired' else 'failed' end,lease_token=null
    where state='pending' and leased_until<=now() and (expires_at<=now() or attempts>=8);
  foreach v_kind in array array['WEEKLY','MONTHLY'] loop
    v_start:=date_trunc(case when v_kind='WEEKLY' then 'week' else 'month' end,v_local)::date;
    v_due:=(v_start::timestamp+interval '8 hours') at time zone 'America/Bogota';
    if p_now<v_due or v_due<v_active then continue; end if;
    v_key:=lower(v_kind)||':'||v_start;
    if exists(select 1 from public.scanner_telegram_jobs where dedupe_key=v_key) then continue; end if;
    insert into public.scanner_telegram_jobs(dedupe_key,kind,payload,expires_at)
      values(v_key,v_kind,public.scanner_telegram_report((v_start-case when v_kind='WEEKLY' then interval '7 days' else interval '1 month' end)::date,v_start-1),p_now+interval '2 days')
      on conflict(dedupe_key) do nothing;
  end loop;
  -- Bounded delivery metadata retention; never touch the scanner's ledger.
  delete from public.scanner_telegram_jobs where (state='sent' and sent_at<now()-interval '45 days') or (state in ('failed','expired') and created_at<now()-interval '45 days');
  perform public.dispatch_scanner_telegram();
end; $$;

revoke execute on function public.dispatch_scanner_telegram(),public.enqueue_scanner_telegram_event(),public.claim_scanner_telegram_job(),public.finish_scanner_telegram_job(bigint,uuid,text,bigint,integer,text),public.scanner_telegram_report(date,date),public.enqueue_scanner_telegram_reports(timestamptz) from public,anon,authenticated;
grant execute on function public.dispatch_scanner_telegram(),public.claim_scanner_telegram_job(),public.finish_scanner_telegram_job(bigint,uuid,text,bigint,integer,text),public.scanner_telegram_report(date,date),public.enqueue_scanner_telegram_reports(timestamptz) to service_role;
do $$ begin
  if exists(select 1 from pg_extension where extname='pg_cron') then
    if exists(select 1 from cron.job where jobname='galaxy-scanner-telegram') then perform cron.unschedule('galaxy-scanner-telegram'); end if;
    if exists(select 1 from cron.job where jobname='galaxy-scanner-telegram-reports') then perform cron.unschedule('galaxy-scanner-telegram-reports'); end if;
    perform cron.schedule('galaxy-scanner-telegram','10 seconds','select public.dispatch_scanner_telegram();');
    perform cron.schedule('galaxy-scanner-telegram-reports','0 * * * *','select public.enqueue_scanner_telegram_reports();');
  end if;
end $$;
notify pgrst,'reload schema';
commit;
